// Copies what the site takes from the Citadel Unity tree, which owns all of it: the design tokens and font
// (visual style, not game data) and, for the grid tests, the game's rotation tables. Game data (stat wording,
// the affinity layout, the fitting grid's drawing data, item art) comes from the game data API at run time,
// with the catalog. The outputs are committed, so builds and tests need nothing from the monorepo; never
// edit them. Re-run this when those Unity files change:
//   node scripts/sync-unity.mjs <citadel monorepo checkout>
import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The Unity files the outputs come from, in a monorepo checkout at `repo`. */
export function sources(repo) {
  const unityRoot = join(resolve(repo), "src/Citadel.Unity");
  // The same five sheets the UI prototype imports in ui-prototype/src/main.tsx.
  const sheets = ["color", "typography", "spacing", "sizing", "components"].map((name) =>
    join(unityRoot, `Assets/Scripts/Runtime/ArenaUI/DesignSystem/tokens/tokens.${name}.uss`),
  );
  return {
    sheets,
    font: join(unityRoot, "ui-prototype/public/fonts/VCROSDNEUE.ttf"),
    // The rotation tables ModuleShapeMask exports for the UI prototype.
    fitting: join(unityRoot, "Assets/Scripts/Runtime/ArenaUI/Panels/Fitting/UI/FittingPanel.fixture.json"),
  };
}

export const OUTPUTS = {
  tokens: join(appRoot, "src/app/game-tokens.generated.css"),
  font: join(appRoot, "src/app/fonts/VCROSDNEUE.ttf"),
  cardTokens: join(appRoot, "src/app/card-tokens.generated.json"),
  rotationTables: join(appRoot, "src/components/grid/rotation-tables.generated.json"),
};

/** USS is a CSS subset: keep the custom properties, drop what only Unity understands. */
export function ussTokensToCss(uss) {
  const root = postcss.parse(uss);
  root.walkDecls((decl) => {
    // `-unity-*` properties and `resource("Fonts/...")` values have no browser meaning; the site
    // binds --font-family to the loaded font in globals.css.
    if (decl.prop.startsWith("-unity-") || decl.value.includes("resource(")) decl.remove();
  });
  // Drop rules left empty, and Unity-only utility classes (.u-*) that exist to set -unity-* props.
  root.walkRules((rule) => {
    if (rule.nodes.length === 0 || /^\.u-/.test(rule.selector)) rule.remove();
  });
  return root.toString();
}

export function buildTokensCss(sheets, at = "") {
  const banner = `/* Generated by scripts/sync-unity.mjs from the Citadel Unity design tokens${at}. Do not edit. */\n`;
  return banner + sheets.map((file) => ussTokensToCss(readFileSync(file, "utf8"))).join("\n");
}

// Token values the share card (next/og, which can't read CSS variables) draws with.
const CARD_TOKENS = ["panel-bg", "header-bg", "text-primary", "text-primary-muted", "text-secondary", "accent-orange", "accent-muted", "state-positive", "state-negative", "state-quantity"];
const TIERS = ["standard", "augmented", "prototype", "artifact", "regalia", "harmonic", "heretical"];

/** Resolved values of colour tokens from the token sheet, for renderers without CSS variables. */
export function tokenValues(css, names) {
  const values = Object.fromEntries([...css.matchAll(/--([\w-]+):\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]));
  return Object.fromEntries(
    names.map((name) => {
      let value = values[name];
      for (let depth = 0; value?.startsWith("var(") && depth < 4; depth++) value = values[value.slice(6, -1)];
      if (!value) throw new Error(`The token sheets have no colour --${name}.`);
      return [name, value];
    }),
  );
}

/**
 * The token values the share card draws with (next/og can't read CSS variables): the card's colours and each
 * tier's surface, border and base colour.
 */
export function buildCardTokens(tokens) {
  const tiers = Object.fromEntries(
    TIERS.map((tier) => {
      const value = tokenValues(tokens, [`tier-${tier}-surface-bg`, `tier-${tier}-surface-base-border`, `tier-${tier}-base`]);
      return [tier, { bg: value[`tier-${tier}-surface-bg`], border: value[`tier-${tier}-surface-base-border`], base: value[`tier-${tier}-base`] }];
    }),
  );
  return { tokens: tokenValues(tokens, CARD_TOKENS), tiers };
}

/** " at monorepo commit <sha>", so the outputs say which Unity files they hold; empty outside a git checkout. */
function at(repo) {
  try {
    const commit = execFileSync("git", ["-C", repo, "rev-parse", "--short=10", "HEAD"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
    return ` at monorepo commit ${commit}`;
  } catch {
    return "";
  }
}

export function sync(repo) {
  const { sheets, font, fitting } = sources(repo);
  for (const file of [...sheets, font, fitting]) {
    if (!existsSync(file)) throw new Error(`Missing design file ${file}. Pass the root of a Citadel monorepo checkout.`);
  }
  for (const file of Object.values(OUTPUTS)) mkdirSync(dirname(file), { recursive: true });
  const css = buildTokensCss(sheets, at(repo));
  writeFileSync(OUTPUTS.tokens, css);
  copyFileSync(font, OUTPUTS.font);
  writeFileSync(OUTPUTS.cardTokens, `${JSON.stringify(buildCardTokens(css), null, 1)}\n`);
  const { rotations, origins, shapes, footprints } = JSON.parse(readFileSync(fitting, "utf8"));
  const tables = { $comment: `Generated by scripts/sync-unity.mjs from FittingPanel.fixture.json${at(repo)}. Do not edit.`, rotations, origins, shapes, footprints };
  writeFileSync(OUTPUTS.rotationTables, `${JSON.stringify(tables)}\n`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const repo = process.argv[2];
  if (!repo) {
    console.error("usage: node scripts/sync-unity.mjs <citadel monorepo checkout>");
    process.exit(1);
  }
  sync(repo);
}
